/// A single-byte encoding by (case-insensitive) name.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum SingleByte {
    Ascii,
    Latin1,
    Table(&'static Upper),
}

pub fn single_byte(name: &[u8]) -> Option<SingleByte> {
    let up = name.to_ascii_uppercase();
    Some(match &up[..] {
        b"US-ASCII" | b"ASCII" => SingleByte::Ascii,
        b"ISO-8859-1" | b"ISO8859-1" | b"ISO_8859-1" | b"LATIN1" | b"L1" | b"ISO-LATIN-1" => {
            SingleByte::Latin1
        }
        b"ISO-8859-2" | b"ISO8859-2" | b"ISO_8859-2" | b"LATIN2" | b"L2" | b"ISO-LATIN-2" => {
            SingleByte::Table(&ISO_8859_2)
        }
        b"ISO-8859-15" | b"ISO8859-15" | b"ISO_8859-15" | b"LATIN-9" | b"LATIN9" => {
            SingleByte::Table(&ISO_8859_15)
        }
        b"WINDOWS-1252" | b"CP1252" => SingleByte::Table(&CP1252),
        _ => return None,
    })
}

impl SingleByte {
    fn cp_of(self, b: u8) -> Option<u32> {
        match self {
            _ if b < 0x80 => Some(b as u32),
            SingleByte::Ascii => None,
            SingleByte::Latin1 => Some(b as u32),
            SingleByte::Table(t) => match t[(b - 0x80) as usize] {
                0 => None,
                cp => Some(cp as u32),
            },
        }
    }

    fn byte_of(self, cp: u32) -> Option<u8> {
        if cp < 0x80 {
            return Some(cp as u8);
        }
        match self {
            SingleByte::Ascii => None,
            SingleByte::Latin1 => (cp <= 0xFF).then_some(cp as u8),
            SingleByte::Table(t) => t
                .iter()
                .position(|&x| x as u32 == cp && x != 0)
                .map(|i| (i + 0x80) as u8),
        }
    }

    /// Bytes in this encoding → UTF-8. Unmapped bytes keep their value as a
    /// code point.
    pub fn decode(self, bytes: &[u8]) -> Vec<u8> {
        let mut out = Vec::with_capacity(bytes.len());
        for &b in bytes {
            let cp = self.cp_of(b).unwrap_or(b as u32);
            if let Some(ch) = char::from_u32(cp) {
                let mut buf = [0u8; 4];
                out.extend_from_slice(ch.encode_utf8(&mut buf).as_bytes());
            }
        }
        out
    }

    /// UTF-8 → this encoding; characters it can't represent become decimal
    /// character references (libxml2's output escaping).
    pub fn encode(self, s: &[u8]) -> Vec<u8> {
        let mut out = Vec::with_capacity(s.len());
        let mut i = 0;
        while i < s.len() {
            if s[i] < 0x80 {
                out.push(s[i]);
                i += 1;
                continue;
            }
            match utf8_char(&s[i..]) {
                Some((cp, len)) => {
                    match self.byte_of(cp) {
                        Some(b) => out.push(b),
                        None => out.extend_from_slice(format!("&#{cp};").as_bytes()),
                    }
                    i += len;
                }
                None => {
                    out.push(s[i]);
                    i += 1;
                }
            }
        }
        out
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn round_trips() {
        let cp = single_byte(b"windows-1252").unwrap();
        assert_eq!(cp.decode(b"\x80"), "€".as_bytes());
        assert_eq!(cp.encode("€ü☺".as_bytes()), b"\x80\xfc&#9786;");
        let l2 = single_byte(b"iso-8859-2").unwrap();
        assert_eq!(l2.decode(b"\xb1"), "ą".as_bytes());
        let l9 = single_byte(b"ISO-8859-15").unwrap();
        assert_eq!(l9.encode("€".as_bytes()), b"\xa4");
        assert_eq!(
            single_byte(b"ascii").unwrap().encode("é".as_bytes()),
            b"&#233;"
        );
    }
}
