//! `gen zip-consts --php-src <dir> [--check]`: `ZipArchive`'s class
//! constants, as a C include for ext/zip's shim. Names, types, C values
//! (`@cvalue`), `#if` guards and attributes come from php-src's
//! `ext/zip/php_zip.stub.php`, in declaration order; the shim compiles them
//! against the linked libzip's zip.h, so every value and every guard is the
//! linked libzip's.

use std::fmt::Write as _;
use std::path::Path;
use std::process::ExitCode;

use super::util::{finish, flag, read};

const OUT: &str = "crates/rhp-builtins/src/ext/zip/consts.h";
const STUB: &str = "ext/zip/php_zip.stub.php";

pub fn main(args: &[String]) -> ExitCode {
    let check = args.iter().any(|a| a == "--check");
    finish("zip-consts", check, files(args))
}

fn files(args: &[String]) -> Result<Vec<(&'static str, String)>, String> {
    let src = flag(args, "--php-src").ok_or("gen zip-consts needs --php-src <php-src checkout>")?;
    let text = read(&Path::new(src).join(STUB))?;
    let mut o = String::from(
        "/* ZipArchive's class constants, in declaration order: names, types,\n \
         * C values (@cvalue), guards and attributes from php-src's\n \
         * ext/zip/php_zip.stub.php. The shim gives each value from the linked\n \
         * libzip's zip.h. Generated by `rhp-difftest gen zip-consts`; do not edit. */\n",
    );
    o.push_str(&constants(&text).map_err(|e| format!("{STUB}: {e}"))?);
    Ok(vec![(OUT, o)])
}

/// A preprocessor block: its `#if` and later `#elif`/`#else` lines, and
/// whether they are in the output yet (only blocks holding a constant are).
struct Block {
    lines: Vec<String>,
    emitted: bool,
}

/// The `RHP_ZIP_INT`/`RHP_ZIP_STR` lines for the class constants of the
/// stub's `ZipArchive`. The last argument is the PHP attribute text to put
/// before the constant ("" for none).
fn constants(text: &str) -> Result<String, String> {
    let mut out = String::new();
    let mut blocks: Vec<Block> = Vec::new();
    let mut cvalue: Option<String> = None;
    let mut attr = String::new();
    let mut in_class = false;
    for line in text.lines() {
        if let Some(d) = line.strip_prefix('#') {
            if !d.starts_with('[') {
                let word = d.split_whitespace().next().unwrap_or("");
                match word {
                    "if" | "ifdef" | "ifndef" => blocks.push(Block {
                        lines: vec![line.trim_end().to_string()],
                        emitted: false,
                    }),
                    "elif" | "else" => {
                        let b = blocks.last_mut().ok_or("#else without #if")?;
                        if b.emitted {
                            writeln!(out, "{}", line.trim_end()).unwrap();
                        } else {
                            b.lines.push(line.trim_end().to_string());
                        }
                    }
                    "endif" => {
                        let b = blocks.pop().ok_or("#endif without #if")?;
                        if b.emitted {
                            out.push_str("#endif\n");
                        }
                    }
                    _ => {}
                }
                continue;
            }
        }
        let t = line.trim();
        if t.starts_with("class ZipArchive") {
            in_class = true;
            continue;
        }
        if !in_class {
            continue;
        }
        if t == "}" && !line.starts_with(' ') {
            in_class = false;
            continue;
        }
        if let Some(i) = t.find("@cvalue ") {
            let v = t[i + 8..].split_whitespace().next().unwrap_or("");
            cvalue = Some(v.to_string());
        } else if t.starts_with("#[") {
            attr = t.to_string();
        } else if let Some(rest) = t.strip_prefix("public const ") {
            let mut words = rest.split_whitespace();
            let ty = words.next().unwrap_or("");
            let name = words.next().unwrap_or("");
            let Some(cvalue) = cvalue.take() else {
                return Err(format!("const {name} has no @cvalue"));
            };
            let kind = match ty {
                "int" => "INT",
                "string" => "STR",
                other => return Err(format!("const {name}: unsupported type {other}")),
            };
            for b in blocks.iter_mut().filter(|b| !b.emitted) {
                for l in &b.lines {
                    writeln!(out, "{l}").unwrap();
                }
                b.emitted = true;
            }
            writeln!(
                out,
                "RHP_ZIP_{kind}(\"{name}\", {cvalue}, \"{}\")",
                attr.replace('\\', "\\\\").replace('"', "\\\"")
            )
            .unwrap();
            attr.clear();
        } else if t.starts_with("public function ") || t.starts_with("public int ") {
            cvalue = None;
            attr.clear();
        }
    }
    if !blocks.is_empty() {
        return Err("unterminated #if".into());
    }
    Ok(out)
}

#[cfg(test)]
mod tests {
    use super::constants;

    #[test]
    fn guards_and_attributes() {
        let stub = "<?php\n/** @cvalue NOPE */\nconst G = UNKNOWN;\n\
                    class ZipArchive implements Countable\n{\n\
                    \x20   /**\n     * @cvalue ZIP_CREATE\n     */\n    public const int CREATE = UNKNOWN;\n\
                    #ifdef ZIP_RDONLY\n    /**\n     * @cvalue ZIP_RDONLY\n     */\n    public const int RDONLY = UNKNOWN;\n#endif\n\
                    #ifdef X\n    /** @cvalue ZIP_FL_RECOMPRESS */\n    #[\\Deprecated(since: '8.3')]\n    public const int FL_RECOMPRESS = UNKNOWN;\n#endif\n\
                    #ifdef Y\n    public function f(): void {}\n#endif\n\
                    \x20   /** @cvalue LIBZIP_VERSION_STR */\n    public const string LIBZIP_VERSION = UNKNOWN;\n}\n";
        assert_eq!(
            constants(stub).unwrap(),
            "RHP_ZIP_INT(\"CREATE\", ZIP_CREATE, \"\")\n\
             #ifdef ZIP_RDONLY\nRHP_ZIP_INT(\"RDONLY\", ZIP_RDONLY, \"\")\n#endif\n\
             #ifdef X\nRHP_ZIP_INT(\"FL_RECOMPRESS\", ZIP_FL_RECOMPRESS, \"#[\\\\Deprecated(since: '8.3')]\")\n#endif\n\
             RHP_ZIP_STR(\"LIBZIP_VERSION\", LIBZIP_VERSION_STR, \"\")\n"
        );
    }
}
