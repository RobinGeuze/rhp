#!/bin/sh
# Write glue/prefix_lexbor.h: an rhp_ prefix for every global symbol the
# lexbor archive defines (see glue/prefix_timelib.h). Compiles the sources
# build.rs compiles, without the prefix, and lists their symbols with nm.
# Run it after sync-php-src-c.sh brings a new lexbor.
#
#   crates/rhp-csrc/tools/gen-prefix-lexbor.sh
set -eu

crate=$(cd "$(dirname "$0")/.." && pwd)
dir=$crate/vendor/php-src/ext/lexbor
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

srcs=$(grep -oE '\$LEXBOR_DIR/[^ ]+\.c' "$dir/config.m4" | sed 's|\$LEXBOR_DIR/||' |
	grep -v -e '^url/' -e '^punycode/' -e '^unicode/')
i=0
for f in $srcs; do
	i=$((i + 1))
	${CC:-cc} -c -O0 -w -DLEXBOR_STATIC -I "$dir" -o "$tmp/$i.o" "$dir/lexbor/$f"
done
${CC:-cc} -c -O0 -w -DLEXBOR_STATIC -I "$dir" -I "$crate/shim" -o "$tmp/glue.o" "$crate/glue/lexbor.c"

{
	cat <<'H'
/*
 * Force-included (-include) into every C file of the lexbor archive, and
 * into ext/dom's lexbor glue in rhp-builtins. Gives each global symbol
 * lexbor defines an rhp_ prefix (see prefix_timelib.h). Generated by
 * tools/gen-prefix-lexbor.sh.
 */
#ifndef RHP_PREFIX_LEXBOR_H
#define RHP_PREFIX_LEXBOR_H

H
	nm -g -P "$tmp"/*.o | awk 'NF >= 2 && $2 !~ /^[Uwv]$/ { print $1 }' | sed 's/^_//' |
		grep -v '^rhp_' | LC_ALL=C sort -u | awk '{ print "#define " $1 " rhp_" $1 }'
	printf '\n#endif\n'
} >"$crate/glue/prefix_lexbor.h"
