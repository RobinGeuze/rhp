<?php
// Generates icu_tables.rs from the ICU linked into the reference php:
//
//     php crates/rhp-builtins/src/ext/intl/gen_icu_tables.php \
//         > crates/rhp-builtins/src/ext/intl/icu_tables.rs
//
// Re-run it (and check the result into git) whenever the reference php's
// ICU (INTL_ICU_VERSION) changes.

if (!extension_loaded('intl') || !extension_loaded('mbstring')) {
    fwrite(STDERR, "needs intl and mbstring\n");
    exit(1);
}

/** Collapses a sorted list of code points into inclusive ranges. */
function ranges(array $cps): array
{
    $out = [];
    foreach ($cps as $cp) {
        $n = count($out);
        if ($n && $out[$n - 1][1] === $cp - 1) {
            $out[$n - 1][1] = $cp;
        } else {
            $out[] = [$cp, $cp];
        }
    }
    return $out;
}

$coll = new Collator('');
$coll->setStrength(Collator::TERTIARY);
$ignorable = [];
$fold = [];
$raw = [];
for ($cp = 0; $cp <= 0x10FFFF; $cp++) {
    if ($cp >= 0xD800 && $cp <= 0xDFFF) {
        continue;
    }
    $c = mb_chr($cp, 'UTF-8');
    // Completely ignorable in root collation: "a<c>b" sorts equal to "ab"
    // (the same set at secondary strength, as of ICU 79).
    if ($coll->compare("a{$c}b", 'ab') === 0) {
        $ignorable[] = $cp;
    }
    // Simple case folding ICU has but php's mbstring tables lack, kept when
    // ICU's NFKC_Casefold agrees with it.
    $icu = IntlChar::foldCase($cp);
    $mb = mb_ord(mb_convert_case($c, MB_CASE_FOLD_SIMPLE, 'UTF-8'), 'UTF-8');
    if ($icu !== $mb && normalizer_normalize($c, Normalizer::NFKC_CF)
            === normalizer_normalize(mb_chr($icu, 'UTF-8'), Normalizer::NFKC_CF)) {
        $fold[] = [$cp, $icu];
    }
    // Raw (one-level) compatibility decompositions that differ from the
    // canonical raw mapping, or failing that the full NFKD, which is what
    // ICU4X can compute.
    $rk = normalizer_get_raw_decomposition($c, Normalizer::FORM_KD);
    $nfkd = normalizer_normalize($c, Normalizer::FORM_KD);
    $model = normalizer_get_raw_decomposition($c, Normalizer::FORM_D) ?? ($nfkd !== $c ? $nfkd : null);
    if ($rk !== $model) {
        $raw[] = [$cp, $rk];
    }
}

$emit = function (string $name, string $doc, array $rs): void {
    echo "\n/// $doc\n";
    echo "pub(super) static $name: &[(u32, u32)] = &[\n";
    foreach ($rs as [$a, $b]) {
        printf("    (0x%04X, 0x%04X),\n", $a, $b);
    }
    echo "];\n";
};

echo "//! Tables derived from ICU ", INTL_ICU_VERSION, " (Unicode ",
    implode('.', array_slice(IntlChar::getUnicodeVersion(), 0, 2)), ") as linked into php ",
    PHP_VERSION, ".\n";
echo "//! Generated by gen_icu_tables.php; do not edit.\n";
$emit('IGNORABLE', 'Code points that are completely ignorable in root collation (inclusive ranges).', ranges($ignorable));
echo "\n/// Raw compatibility decompositions (code point, mapping) that are neither\n";
echo "/// the canonical raw mapping nor the full NFKD.\n";
echo "pub(super) static RAW_COMPAT: &[(u32, &str)] = &[\n";
foreach ($raw as [$cp, $m]) {
    $esc = '';
    foreach (mb_str_split($m, 1, 'UTF-8') as $ch) {
        $o = mb_ord($ch, 'UTF-8');
        $esc .= $o >= 0x20 && $o < 0x7F && $ch !== '"' && $ch !== '\\' ? $ch : sprintf('\\u{%X}', $o);
    }
    printf("    (0x%04X, \"%s\"),\n", $cp, $esc);
}
echo "];\n";
$emit('FOLD_EXTRA', "Simple case foldings (code point, folded) where ICU differs from mbstring's tables.", $fold);
