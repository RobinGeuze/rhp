//! `gen sockets-consts --php-src <dir> [--check]`: ext/sockets' constants,
//! as a C include for its shim. Names, C values (`@cvalue`) and `#if`
//! guards come from php-src's `ext/sockets/sockets.stub.php`, in
//! declaration order; the shim compiles them against the system's socket
//! headers, so every value and every guard is the platform's, as in php.

use std::fmt::Write as _;
use std::path::Path;
use std::process::ExitCode;

use super::util::{finish, flag, read};

const OUT: &str = "crates/rhp-builtins/src/ext/sockets/consts.h";
const STUB: &str = "ext/sockets/sockets.stub.php";

pub fn main(args: &[String]) -> ExitCode {
    let check = args.iter().any(|a| a == "--check");
    finish("sockets-consts", check, files(args))
}

fn files(args: &[String]) -> Result<Vec<(&'static str, String)>, String> {
    let src =
        flag(args, "--php-src").ok_or("gen sockets-consts needs --php-src <php-src checkout>")?;
    let text = read(&Path::new(src).join(STUB))?;
    let mut o = String::from(
        "/* ext/sockets' constants, in declaration order: names, C values\n \
         * (@cvalue) and guards from php-src's ext/sockets/sockets.stub.php.\n \
         * The shim gives each value from the system's headers. Generated by\n \
         * `rhp-difftest gen sockets-consts`; do not edit. */\n",
    );
    o.push_str(&constants(&text).map_err(|e| format!("{STUB}: {e}"))?);
    Ok(vec![(OUT, o)])
}

/// A preprocessor block: its `#if` and later `#elif`/`#else` lines, and
/// whether they are in the output yet (only blocks holding a constant are).
struct Block {
    lines: Vec<String>,
    emitted: bool,
}

/// One `RHP_SOCKETS_INT(name, value)` line per global constant of the stub,
/// inside the `#if` blocks that guard it.
fn constants(text: &str) -> Result<String, String> {
    let mut out = String::new();
    let mut blocks: Vec<Block> = Vec::new();
    let mut cvalue: Option<String> = None;
    for line in text.lines() {
        if let Some(d) = line.strip_prefix('#') {
            if !d.starts_with('[') {
                match d.split_whitespace().next().unwrap_or("") {
                    "if" | "ifdef" | "ifndef" => blocks.push(Block {
                        lines: vec![line.trim_end().to_string()],
                        emitted: false,
                    }),
                    "elif" | "else" => {
                        let b = blocks.last_mut().ok_or("#else without #if")?;
                        if b.emitted {
                            writeln!(out, "{}", line.trim_end()).unwrap();
                        } else {
                            b.lines.push(line.trim_end().to_string());
                        }
                    }
                    "endif" => {
                        let b = blocks.pop().ok_or("#endif without #if")?;
                        if b.emitted {
                            out.push_str("#endif\n");
                        }
                    }
                    _ => {}
                }
                continue;
            }
        }
        let t = line.trim();
        if let Some(i) = t.find("@cvalue ") {
            let v = t[i + 8..].split_whitespace().next().unwrap_or("");
            cvalue = Some(v.to_string());
        } else if let Some(rest) = line.strip_prefix("const ") {
            let name = rest.split_whitespace().next().unwrap_or("");
            let Some(cvalue) = cvalue.take() else {
                return Err(format!("const {name} has no @cvalue"));
            };
            for b in blocks.iter_mut().filter(|b| !b.emitted) {
                for l in &b.lines {
                    writeln!(out, "{l}").unwrap();
                }
                b.emitted = true;
            }
            writeln!(out, "RHP_SOCKETS_INT(\"{name}\", {cvalue})").unwrap();
        } else if t.starts_with("function ") || t.starts_with("final class ") {
            cvalue = None;
        }
    }
    if !blocks.is_empty() {
        return Err("unterminated #if".into());
    }
    Ok(out)
}

#[cfg(test)]
mod tests {
    use super::constants;

    #[test]
    fn guards() {
        let stub = "<?php\n/**\n * @var int\n * @cvalue AF_UNIX\n */\nconst AF_UNIX = UNKNOWN;\n\
                    #ifdef HAVE_IPV6\n/** @cvalue AF_INET6 */\nconst AF_INET6 = UNKNOWN;\n#endif\n\
                    #if defined(A) || defined(B)\n/** @cvalue X */\nconst X = UNKNOWN;\n#else\n\
                    /** @cvalue Y */\nconst X = UNKNOWN;\n#endif\n\
                    #ifdef HAVE_SHUTDOWN\nfunction socket_shutdown(): bool {}\n#endif\n";
        assert_eq!(
            constants(stub).unwrap(),
            "RHP_SOCKETS_INT(\"AF_UNIX\", AF_UNIX)\n\
             #ifdef HAVE_IPV6\nRHP_SOCKETS_INT(\"AF_INET6\", AF_INET6)\n#endif\n\
             #if defined(A) || defined(B)\nRHP_SOCKETS_INT(\"X\", X)\n#else\nRHP_SOCKETS_INT(\"X\", Y)\n#endif\n"
        );
    }
}
