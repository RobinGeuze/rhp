//! `gen intl-consts --php-src <dir> [--check]`: the global constants
//! ext/intl registers and the class constants of the classes rhp
//! implements, as C includes for its shim. Names, types, C values
//! (`@cvalue`), `#if` guards and attributes come from php-src's stubs, in
//! the order php registers them; the shim compiles them against the linked
//! ICU's headers, so every value is the linked ICU's.

use std::fmt::Write as _;
use std::path::Path;
use std::process::ExitCode;

use super::util::{finish, flag, read};

const OUT: &str = "crates/rhp-builtins/src/ext/intl/consts.h";
const CLASS_OUT: &str = "crates/rhp-builtins/src/ext/intl/class_consts.h";

/// The stubs declaring global constants, in php_intl.c's MINIT order.
const STUBS: &[&str] = &[
    "ext/intl/php_intl.stub.php",
    "ext/intl/collator/collator.stub.php",
    "ext/intl/common/common.stub.php",
];

/// The stubs whose classes rhp implements, with the class names, in
/// php_intl.c's MINIT order.
const CLASS_STUBS: &[(&str, &str)] = &[
    ("ext/intl/collator/collator.stub.php", "Collator"),
    ("ext/intl/formatter/formatter.stub.php", "NumberFormatter"),
    ("ext/intl/locale/locale.stub.php", "Locale"),
    (
        "ext/intl/dateformat/dateformat.stub.php",
        "IntlDateFormatter",
    ),
    (
        "ext/intl/transliterator/transliterator.stub.php",
        "Transliterator",
    ),
    ("ext/intl/timezone/timezone.stub.php", "IntlTimeZone"),
    ("ext/intl/calendar/calendar.stub.php", "IntlCalendar"),
    (
        "ext/intl/spoofchecker/spoofchecker.stub.php",
        "Spoofchecker",
    ),
    (
        "ext/intl/breakiterator/breakiterator.stub.php",
        "IntlBreakIterator",
    ),
    (
        "ext/intl/breakiterator/breakiterator_iterators.stub.php",
        "IntlPartsIterator",
    ),
    ("ext/intl/uchar/uchar.stub.php", "IntlChar"),
];

pub fn main(args: &[String]) -> ExitCode {
    let check = args.iter().any(|a| a == "--check");
    finish("intl-consts", check, files(args))
}

fn files(args: &[String]) -> Result<Vec<(&'static str, String)>, String> {
    let src =
        flag(args, "--php-src").ok_or("gen intl-consts needs --php-src <php-src checkout>")?;
    let mut o = String::from(
        "/* php's global intl constants, in registration order: names, types,\n \
         * C values (@cvalue) and guards from php-src's ext/intl stubs. The shim\n \
         * gives each value from the linked ICU's headers.\n \
         * Generated by `rhp-difftest gen intl-consts`; do not edit. */\n",
    );
    for stub in STUBS {
        let text = read(&Path::new(src).join(stub))?;
        writeln!(o, "/* {stub} */").unwrap();
        o.push_str(&constants(&text).map_err(|e| format!("{stub}: {e}"))?);
    }
    let mut c = String::from(
        "/* The class constants of the intl classes rhp implements, in\n \
         * declaration order: classes, names, types, C values (@cvalue), guards\n \
         * and attributes from php-src's ext/intl stubs. The shim gives each\n \
         * value from the linked ICU's headers (php's own macros: shim.c).\n \
         * Generated by `rhp-difftest gen intl-consts`; do not edit. */\n",
    );
    for (stub, class) in CLASS_STUBS {
        let text = read(&Path::new(src).join(stub))?;
        writeln!(c, "/* {stub} */").unwrap();
        c.push_str(&class_constants(&text, class).map_err(|e| format!("{stub}: {e}"))?);
    }
    Ok(vec![(OUT, o), (CLASS_OUT, c)])
}

/// A preprocessor block: its `#if` and later `#elif`/`#else` lines, and
/// whether they are in the output yet (only blocks holding a constant are).
struct Block {
    lines: Vec<String>,
    emitted: bool,
}

/// The `RHP_INTL_INT`/`RHP_INTL_STR` lines for a stub's global constants.
fn constants(text: &str) -> Result<String, String> {
    let mut out = String::new();
    let mut blocks: Vec<Block> = Vec::new();
    let mut ty: Option<String> = None;
    let mut cvalue: Option<String> = None;
    for line in text.lines() {
        if let Some(d) = line.strip_prefix('#') {
            let word = d.split_whitespace().next().unwrap_or("");
            match word {
                "if" | "ifdef" | "ifndef" => blocks.push(Block {
                    lines: vec![line.trim_end().to_string()],
                    emitted: false,
                }),
                "elif" | "else" => {
                    let b = blocks.last_mut().ok_or("#else without #if")?;
                    if b.emitted {
                        writeln!(out, "{}", line.trim_end()).unwrap();
                    } else {
                        b.lines.push(line.trim_end().to_string());
                    }
                }
                "endif" => {
                    let b = blocks.pop().ok_or("#endif without #if")?;
                    if b.emitted {
                        out.push_str("#endif\n");
                    }
                }
                _ => {}
            }
            continue;
        }
        let t = line.trim();
        if let Some(v) = t.strip_prefix("* @var ") {
            ty = Some(v.trim().to_string());
        } else if let Some(v) = t.strip_prefix("* @cvalue ") {
            cvalue = Some(v.trim().to_string());
        } else if let Some(rest) = line.strip_prefix("const ") {
            // A global constant (class constants are indented).
            let name = rest
                .split(|c: char| c.is_whitespace() || c == '=')
                .next()
                .unwrap_or("");
            let (Some(ty), Some(cvalue)) = (ty.take(), cvalue.take()) else {
                return Err(format!("const {name} has no @var or @cvalue"));
            };
            let kind = match ty.as_str() {
                "int" => "INT",
                "string" => "STR",
                other => return Err(format!("const {name}: unsupported @var {other}")),
            };
            for b in blocks.iter_mut().filter(|b| !b.emitted) {
                for l in &b.lines {
                    writeln!(out, "{l}").unwrap();
                }
                b.emitted = true;
            }
            writeln!(out, "RHP_INTL_{kind}(\"{name}\", {cvalue})").unwrap();
        } else if t.starts_with("function ") || t.starts_with("class ") {
            ty = None;
            cvalue = None;
        }
    }
    if !blocks.is_empty() {
        return Err("unterminated #if".into());
    }
    Ok(out)
}

/// The `RHP_INTL_CLASS_INT`/`_STR`/`_NULL` lines for the constants of
/// `class` in a stub: class, name, C value, and the PHP attribute text to
/// put before the constant ("" for none).
fn class_constants(text: &str, class: &str) -> Result<String, String> {
    let mut out = String::new();
    let mut blocks: Vec<Block> = Vec::new();
    let mut cvalue: Option<String> = None;
    let mut attr = String::new();
    let mut in_class = false;
    let head = format!("class {class}");
    for line in text.lines() {
        let t = line.trim();
        if let Some(d) = t.strip_prefix('#').filter(|d| !d.starts_with('[')) {
            let word = d.split_whitespace().next().unwrap_or("");
            match word {
                "if" | "ifdef" | "ifndef" => blocks.push(Block {
                    lines: vec![t.to_string()],
                    emitted: false,
                }),
                "elif" | "else" => {
                    let b = blocks.last_mut().ok_or("#else without #if")?;
                    if b.emitted {
                        writeln!(out, "{t}").unwrap();
                    } else {
                        b.lines.push(t.to_string());
                    }
                }
                "endif" => {
                    let b = blocks.pop().ok_or("#endif without #if")?;
                    if b.emitted {
                        out.push_str("#endif\n");
                    }
                }
                _ => {}
            }
            continue;
        }
        if t == head || t.starts_with(&format!("{head} ")) {
            in_class = true;
            continue;
        }
        if !in_class {
            continue;
        }
        if line.starts_with('}') {
            in_class = false;
            continue;
        }
        if let Some(i) = t.find("@cvalue ") {
            let v = t[i + 8..].split_whitespace().next().unwrap_or("");
            cvalue = Some(v.to_string());
        } else if t.starts_with("#[") {
            attr = t.to_string();
        } else if let Some(rest) = t.strip_prefix("public const ") {
            let mut words = rest.split_whitespace();
            let ty = words.next().unwrap_or("");
            let name = words.next().unwrap_or("");
            let (kind, value) = match (ty, cvalue.take()) {
                ("null", None) => ("NULL", "0".to_string()),
                ("int", Some(v)) => ("INT", v),
                ("string", Some(v)) => ("STR", v),
                ("float", Some(v)) => ("FLOAT", v),
                (other, _) => {
                    return Err(format!(
                        "const {name}: unsupported type {other} or no @cvalue"
                    ))
                }
            };
            for b in blocks.iter_mut().filter(|b| !b.emitted) {
                for l in &b.lines {
                    writeln!(out, "{l}").unwrap();
                }
                b.emitted = true;
            }
            writeln!(
                out,
                "RHP_INTL_CLASS_{kind}(\"{class}\", \"{name}\", {value}, \"{}\")",
                attr.replace('\\', "\\\\").replace('"', "\\\"")
            )
            .unwrap();
            attr.clear();
        } else if t.starts_with("public function ") || t.starts_with("public static function ") {
            cvalue = None;
            attr.clear();
        }
    }
    if !blocks.is_empty() {
        return Err("unterminated #if".into());
    }
    Ok(out)
}

