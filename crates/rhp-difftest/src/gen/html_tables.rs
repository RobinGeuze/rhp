//! `gen html-tables --php-src <dir> [--check]`: php's HTML entity and
//! charset tables (ext/standard/html_tables.h) from the inputs of php's own
//! generator, ext/standard/html_tables/html_table_gen.php: the entity lists
//! (ents_*.txt) and the charset mapping files, read the way it reads them.
//!
//! php 8.5's generator does not reproduce the committed html_tables.h: when
//! several HTML5 entities name one code point, it picks with a sort that
//! was unstable when the header was last generated (2014). So for those code
//! points the committed header decides, and every table built from the
//! inputs must otherwise equal the header's.

use std::collections::{BTreeMap, HashMap};
use std::fmt::Write as _;
use std::path::Path;

use super::{emit, flag, read};

const OUT: &str = "crates/rhp-builtins/src/html_tables.rs";

/// Single-byte charsets with a map to Unicode: (php ident, rhp name, file).
/// ISO-8859-1 maps to itself, so php never reads its table.
const TO_UNI: &[(&str, &str, &str)] = &[
    ("win1252", "CP1252", "CP1252.TXT"),
    ("iso885915", "ISO8859_15", "8859-15.TXT"),
    ("win1251", "CP1251", "CP1251.TXT"),
    ("iso88595", "ISO8859_5", "8859-5.TXT"),
    ("cp866", "CP866", "CP866.TXT"),
    ("macroman", "MACROMAN", "ROMAN.TXT"),
    ("koi8r", "KOI8R", "KOI8-R.TXT"),
];

/// Maps from Unicode: (php ident, rhp name, file, byte range).
const FROM_UNI: &[(&str, &str, &str, u32, u32)] = &[
    ("iso885915", "ISO8859_15", "8859-15.TXT", 0xA4, 0xBE),
    ("win1252", "CP1252", "CP1252.TXT", 0x80, 0x9F),
    ("win1251", "CP1251", "CP1251.TXT", 0x80, 0xFF),
    ("koi8r", "KOI8R", "KOI8-R.TXT", 0x80, 0xFF),
    ("cp866", "CP866", "CP866.TXT", 0x80, 0xFF),
    ("macroman", "MACROMAN", "ROMAN.TXT", 0x80, 0xFF),
];

/// Entity tables: (php ident, rhp name, file).
const ENTS: &[(&str, &str, &str)] = &[
    ("html5", "HTML5", "ents_html5.txt"),
    ("html4", "HTML4", "ents_html401.txt"),
    ("be_noapos", "BASIC", "ents_basic.txt"),
    ("be_apos", "BASIC_APOS", "ents_basic_apos.txt"),
];

/// A code point's row in an encoding table.
#[derive(Clone, Debug, PartialEq, Eq)]
enum Row {
    One(String),
    /// The default entity (if any) and (second code point, entity) pairs.
    Multi(Option<String>, Vec<(u32, String)>),
}

pub fn main(args: &[String]) -> Result<bool, String> {
    let check = args.iter().any(|a| a == "--check");
    let src =
        flag(args, "--php-src").ok_or("gen html-tables needs --php-src <php-src checkout>")?;
    let std = Path::new(src).join("ext/standard");
    let dir = std.join("html_tables");
    let header = read(&std.join("html_tables.h"))?;
    emit(OUT, &generate(&dir, &header)?, check)
}

fn generate(dir: &Path, header: &str) -> Result<String, String> {
    let mut o = String::new();
    o.push_str(
        "//! php's HTML entity and charset tables (ext/standard/html_tables.h).\n\
         //!\n\
         //! Generated by `rhp-difftest gen html-tables` from php-src's\n\
         //! ext/standard/html_tables/ (entity lists and charset mapping files), read\n\
         //! as html_table_gen.php reads them; where several HTML5 entities name one\n\
         //! code point, the one php's html_tables.h encodes to. Do not edit.\n\n\
         /// A code point's entry in an encoding table.\n\
         pub enum Enc {\n    \
             One(&'static str),\n    \
             /// `default` unless the next character is one of the second code points.\n    \
             Multi(Option<&'static str>, &'static [(u32, &'static str)]),\n\
         }\n",
    );
    for &(ident, name, file) in ENTS {
        let ents = read_ents(&dir.join(file))?;
        let rows = encode_rows(&ents, header, ident)?;
        let want = header_rows(header, ident)?;
        if rows != want {
            return Err(format!(
                "{file}: the encoding table differs from html_tables.h"
            ));
        }
        let decode = decode_rows(&ents);
        let mut want = header_hash(header, ident)?;
        let mut got: Vec<_> = decode.iter().map(|(n, a, b)| (n.clone(), *a, *b)).collect();
        want.sort();
        got.sort();
        if got != want {
            return Err(format!(
                "{file}: the decoding table differs from html_tables.h"
            ));
        }
        emit_encode(&mut o, name, &rows);
        emit_decode(&mut o, name, &decode);
    }
    for &(ident, name, file) in TO_UNI {
        let map = to_unicode(&read(&dir.join("mappings").join(file))?);
        if map != header_to_uni(header, ident)? {
            return Err(format!(
                "{file}: the map to Unicode differs from html_tables.h"
            ));
        }
        writeln!(
            o,
            "\n/// {file} (0xFFFF: no mapping).\npub static TO_UNI_{name}: [u16; 256] = ["
        )
        .unwrap();
        for chunk in map.chunks(16) {
            let row: Vec<String> = chunk.iter().map(|v| format!("0x{v:04X}")).collect();
            writeln!(o, "    {},", row.join(", ")).unwrap();
        }
        o.push_str("];\n");
    }
    for &(ident, name, file, lo, hi) in FROM_UNI {
        let map = from_unicode(&read(&dir.join("mappings").join(file))?, lo, hi);
        if map != header_from_uni(header, ident)? {
            return Err(format!(
                "{file}: the map from Unicode differs from html_tables.h"
            ));
        }
        writeln!(
            o,
            "\n/// {file}, bytes 0x{lo:02X}..=0x{hi:02X}: (code point, byte), sorted.\n\
             pub static FROM_UNI_{name}: [(u16, u8); {}] = [",
            map.len()
        )
        .unwrap();
        for chunk in map.chunks(8) {
            let row: Vec<String> = chunk
                .iter()
                .map(|(u, b)| format!("(0x{u:04X}, 0x{b:02X})"))
                .collect();
            writeln!(o, "    {},", row.join(", ")).unwrap();
        }
        o.push_str("];\n");
    }
    Ok(o)
}

/// An ents_*.txt file: (name, code point, second code point), in file order.
fn read_ents(path: &Path) -> Result<Vec<(String, u32, Option<u32>)>, String> {
    let mut out = Vec::new();
    for line in read(path)?.lines() {
        // '/^(#?[a-z0-9]+)\s+([a-f0-9]+) ([a-f0-9]+)/i', else without the third
        let b = line.as_bytes();
        let mut i = usize::from(b.first() == Some(&b'#'));
        let ns = i;
        while i < b.len() && b[i].is_ascii_alphanumeric() {
            i += 1;
        }
        if i == ns {
            continue;
        }
        let name = &line[..i];
        let ws = i;
        while i < b.len() && b[i].is_ascii_whitespace() {
            i += 1;
        }
        let hex = |i: &mut usize| {
            let s = *i;
            while *i < b.len() && b[*i].is_ascii_hexdigit() {
                *i += 1;
            }
            (*i > s).then(|| u32::from_str_radix(&line[s..*i], 16).unwrap())
        };
        if i == ws {
            continue;
        }
        let Some(cp) = hex(&mut i) else { continue };
        let mut second = None;
        if b.get(i) == Some(&b' ') {
            let mut j = i + 1;
            second = hex(&mut j);
        }
        out.push((name.to_string(), cp, second));
    }
    Ok(out)
}

/// html_table_gen.php's code point -> entity table, ties settled by the
/// header.
fn encode_rows(
    ents: &[(String, u32, Option<u32>)],
    header: &str,
    ident: &str,
) -> Result<BTreeMap<u32, Row>, String> {
    let theirs = header_rows(header, ident)?;
    let multi: Vec<u32> = ents.iter().filter(|e| e.2.is_some()).map(|e| e.1).collect();
    // candidates per code point (single) and per pair
    let mut single: BTreeMap<u32, Vec<String>> = BTreeMap::new();
    let mut pairs: BTreeMap<(u32, u32), Vec<String>> = BTreeMap::new();
    for (name, cp, second) in ents {
        match second {
            Some(s) => pairs.entry((*cp, *s)).or_default().push(name.clone()),
            None => single.entry(*cp).or_default().push(name.clone()),
        }
    }
    // the generator's hacks: "QUOT" -> "quot" (stage 3), "GT" -> "gt" (default)
    let fix = |n: &str, from: &str, to: &str| {
        if n == from {
            to.to_string()
        } else {
            n.to_string()
        }
    };
    let pick = |cands: &[String], want: Option<&str>, what: String| -> Result<String, String> {
        match cands {
            [one] => Ok(one.clone()),
            _ => match want {
                Some(w) if cands.iter().any(|c| c == w) => Ok(w.to_string()),
                _ => Err(format!(
                    "{ident}: html_tables.h's choice for {what} is not in the input"
                )),
            },
        }
    };
    let mut rows = BTreeMap::new();
    for (&cp, cands) in &single {
        if multi.contains(&cp) {
            continue;
        }
        let want = match theirs.get(&cp) {
            Some(Row::One(n)) => Some(n.as_str()),
            _ => None,
        };
        let name = pick(cands, want, format!("U+{cp:04X}"))?;
        rows.insert(cp, Row::One(fix(&name, "QUOT", "quot")));
    }
    for &cp in &multi {
        if rows.contains_key(&cp) {
            continue;
        }
        let (want_default, want_seconds) = match theirs.get(&cp) {
            Some(Row::Multi(d, s)) => (d.clone(), s.clone()),
            _ => (None, Vec::new()),
        };
        let default = match single.get(&cp) {
            Some(c) => Some(fix(
                &pick(c, want_default.as_deref(), format!("U+{cp:04X}"))?,
                "GT",
                "gt",
            )),
            None => None,
        };
        let mut seconds = Vec::new();
        for (&(a, b), cands) in pairs.range((cp, 0)..=(cp, u32::MAX)) {
            debug_assert_eq!(a, cp);
            let want = want_seconds.iter().find(|s| s.0 == b).map(|s| s.1.as_str());
            seconds.push((b, pick(cands, want, format!("U+{a:04X} U+{b:04X}"))?));
        }
        rows.insert(cp, Row::Multi(default, seconds));
    }
    Ok(rows)
}

/// The entity -> code points map (php's hash table), first entry winning.
fn decode_rows(ents: &[(String, u32, Option<u32>)]) -> Vec<(String, u32, u32)> {
    let mut seen = HashMap::new();
    let mut out = Vec::new();
    for (name, cp, second) in ents {
        if seen.insert(name.clone(), ()).is_none() {
            out.push((name.clone(), *cp, second.unwrap_or(0)));
        }
    }
    out.sort_by(|a, b| a.0.as_bytes().cmp(b.0.as_bytes()));
    out
}

/// A mapping file's byte -> code point table (0xFFFF: unmapped).
fn to_unicode(txt: &str) -> Vec<u16> {
    let mut map = vec![0xFFFFu16; 256];
    for (byte, cp, _) in mapping_lines(txt) {
        map[byte as usize] = cp as u16;
    }
    map
}

/// The code point -> byte map for bytes in lo..=hi, sorted by code point.
fn from_unicode(txt: &str, lo: u32, hi: u32) -> Vec<(u16, u8)> {
    let mut m = BTreeMap::new();
    for (byte, cp, commented) in mapping_lines(txt) {
        if commented && (lo..=hi).contains(&byte) {
            m.insert(cp as u16, byte as u8);
        }
    }
    m.into_iter().collect()
}

/// `0xXX\t0xYYYY` lines: (byte, code point, has a `# name` comment).
fn mapping_lines(txt: &str) -> Vec<(u32, u32, bool)> {
    let mut out = Vec::new();
    for line in txt.lines() {
        let Some(rest) = line.strip_prefix("0x").or_else(|| line.strip_prefix("0X")) else {
            continue;
        };
        let (b, rest) = rest.split_at(rest.len().min(2));
        let Ok(byte) = u32::from_str_radix(b, 16) else {
            continue;
        };
        let Some(rest) = rest
            .strip_prefix("\t0x")
            .or_else(|| rest.strip_prefix("\t0X"))
        else {
            continue;
        };
        let digits: String = rest.chars().take_while(|c| c.is_ascii_hexdigit()).collect();
        if digits.len() < 2 {
            continue;
        }
        let cp = u32::from_str_radix(&digits, 16).unwrap();
        let after = rest[digits.len()..].trim_start();
        out.push((byte, cp, after.starts_with('#')));
    }
    out
}

// --- html_tables.h --------------------------------------------------------

/// The bodies of `static const <ty> <prefix><suffix>[] = { … };`, by suffix.
fn bodies<'a>(header: &'a str, ty: &str, prefix: &str) -> Vec<(&'a str, &'a str)> {
    let pat = format!("static const {ty} {prefix}");
    let mut out = Vec::new();
    let mut rest = header;
    while let Some(i) = rest.find(&pat) {
        rest = &rest[i + pat.len()..];
        let name_end = rest
            .find(|c: char| !(c.is_ascii_alphanumeric() || c == '_'))
            .unwrap_or(0);
        let suffix = &rest[..name_end];
        let open = rest.find('{').unwrap_or(0);
        let close = rest.find("};").unwrap_or(rest.len());
        out.push((suffix, &rest[open + 1..close]));
        rest = &rest[close..];
    }
    out
}

fn quoted(s: &str) -> Option<(&str, &str)> {
    let s = s.strip_prefix('"')?;
    let e = s.find('"')?;
    Some((&s[..e], &s[e + 1..]))
}

/// The header's code point -> entity rows for one table.
fn header_rows(header: &str, ident: &str) -> Result<BTreeMap<u32, Row>, String> {
    let mut multi = HashMap::new();
    for (suffix, body) in bodies(
        header,
        "entity_multicodepoint_row",
        &format!("multi_cp_{ident}_"),
    ) {
        let mut lines = body.lines().filter_map(|l| l.trim().strip_prefix("{ {"));
        let lead = lines.next().ok_or("empty multi_cp row")?.trim_start();
        let default = quoted(lead).map(|(n, _)| n.to_string());
        let mut seconds = Vec::new();
        for l in lines {
            let (name, rest) = quoted(l.trim_start()).ok_or("bad multi_cp entry")?;
            let hex = rest.trim_start_matches([',', ' ', '\t']);
            let hex = hex.strip_prefix("0x").ok_or("bad multi_cp code point")?;
            let digits: String = hex.chars().take_while(|c| c.is_ascii_hexdigit()).collect();
            seconds.push((u32::from_str_radix(&digits, 16).unwrap(), name.to_string()));
        }
        multi.insert(suffix.to_string(), Row::Multi(default, seconds));
    }
    let mut rows = BTreeMap::new();
    for (suffix, body) in bodies(
        header,
        "entity_stage3_row",
        &format!("stage3_table_{ident}_"),
    ) {
        let base =
            u32::from_str_radix(suffix, 16).map_err(|_| format!("bad stage 3 table {suffix}"))?;
        let mut rest = body;
        let mut k = 0;
        while let Some(i) = rest.find(", { {") {
            let flag = &rest[..i];
            rest = &rest[i + 5..];
            let cp = base + k;
            k += 1;
            if flag.ends_with("{1") {
                let s = rest.split("multi_cp_").nth(1).ok_or("bad ambiguous row")?;
                let hex: String = s.chars().skip(ident.len() + 1).take(5).collect();
                rows.insert(
                    cp,
                    multi
                        .get(&hex)
                        .cloned()
                        .ok_or(format!("no multi_cp_{ident}_{hex}"))?,
                );
            } else if let Some((name, _)) = quoted(rest) {
                rows.insert(cp, Row::One(name.to_string()));
            }
        }
        if k != 64 {
            return Err(format!("stage3_table_{ident}_{suffix}: {k} rows"));
        }
    }
    Ok(rows)
}

/// The header's entity hash table, as (name, code point, second).
fn header_hash(header: &str, ident: &str) -> Result<Vec<(String, u32, u32)>, String> {
    let mut out = Vec::new();
    for (_, body) in bodies(header, "entity_cp_map", &format!("ht_bucket_{ident}_")) {
        for e in body.split("{\"").skip(1) {
            let name = &e[..e.find('"').ok_or("bad bucket")?];
            let nums: Vec<u32> = e[name.len() + 1..]
                .split(',')
                .map(str::trim)
                .filter(|s| !s.is_empty())
                .take(3)
                .map(|s| {
                    let s = s.trim_end_matches('}');
                    match s.strip_prefix("0x") {
                        Some(h) => u32::from_str_radix(h, 16).unwrap_or(0),
                        None => s.parse().unwrap_or(0),
                    }
                })
                .collect();
            out.push((name.to_string(), nums[1], nums[2]));
        }
    }
    Ok(out)
}

fn header_to_uni(header: &str, ident: &str) -> Result<Vec<u16>, String> {
    let stage2: HashMap<&str, Vec<u16>> = bodies(header, "enc_to_uni_stage2", "enc_to_uni_s2_")
        .into_iter()
        .map(|(name, body)| {
            let v = body
                .split(',')
                .filter_map(|s| s.trim().trim_matches('{').trim().strip_prefix("0x"))
                .map(|h| u16::from_str_radix(h, 16).unwrap())
                .collect();
            (name, v)
        })
        .collect();
    let pat = format!("static const enc_to_uni enc_to_uni_{ident} = {{");
    let i = header.find(&pat).ok_or(format!("no enc_to_uni_{ident}"))?;
    let body = &header[i + pat.len()..];
    let body = &body[..body.find("};").unwrap_or(body.len())];
    let mut out = Vec::new();
    for r in body.split('&').skip(1) {
        let name: String = r
            .trim_start_matches("enc_to_uni_s2_")
            .chars()
            .take_while(|c| c.is_ascii_alphanumeric() || *c == '_')
            .collect();
        out.extend(
            stage2
                .get(name.as_str())
                .ok_or(format!("no stage 2 table {name}"))?,
        );
    }
    Ok(out)
}

fn header_from_uni(header: &str, ident: &str) -> Result<Vec<(u16, u8)>, String> {
    let (_, body) = bodies(header, "uni_to_enc", &format!("unimap_{ident}"))
        .into_iter()
        .find(|(s, _)| s.is_empty())
        .ok_or(format!("no unimap_{ident}"))?;
    let mut out = Vec::new();
    for e in body.split("{ 0x").skip(1) {
        let (u, rest) = e.split_once(", 0x").ok_or("bad unimap entry")?;
        let b: String = rest.chars().take_while(|c| c.is_ascii_hexdigit()).collect();
        out.push((
            u16::from_str_radix(u, 16).unwrap(),
            u8::from_str_radix(&b, 16).unwrap(),
        ));
    }
    Ok(out)
}

// --- output ---------------------------------------------------------------

fn emit_encode(o: &mut String, name: &str, rows: &BTreeMap<u32, Row>) {
    let all_single = rows.values().all(|r| matches!(r, Row::One(_)));
    if all_single && rows.keys().all(|&cp| cp < 64) {
        // the basic tables: php indexes a 64-entry table
        writeln!(o, "\n/// Code point -> entity, by code point.\npub static ENC_{name}: [(u32, &str); {}] = [", rows.len()).unwrap();
        for (cp, r) in rows {
            if let Row::One(n) = r {
                writeln!(o, "    (0x{cp:02X}, {n:?}),").unwrap();
            }
        }
        o.push_str("];\n");
        return;
    }
    writeln!(
        o,
        "\n/// Code point -> entity, by code point.\npub static ENC_{name}: [(u32, Enc); {}] = [",
        rows.len()
    )
    .unwrap();
    for (cp, r) in rows {
        match r {
            Row::One(n) => writeln!(o, "    (0x{cp:05X}, Enc::One({n:?})),").unwrap(),
            Row::Multi(d, s) => {
                let seconds: Vec<String> = s
                    .iter()
                    .map(|(c, n)| format!("(0x{c:05X}, {n:?})"))
                    .collect();
                writeln!(
                    o,
                    "    (0x{cp:05X}, Enc::Multi({d:?}, &[{}])),",
                    seconds.join(", ")
                )
                .unwrap();
            }
        }
    }
    o.push_str("];\n");
}

fn emit_decode(o: &mut String, name: &str, rows: &[(String, u32, u32)]) {
    writeln!(
        o,
        "\n/// Entity -> (code point, second code point or 0), sorted by name.\n\
         pub static DEC_{name}: [(&str, u32, u32); {}] = [",
        rows.len()
    )
    .unwrap();
    for chunk in rows.chunks(4) {
        let row: Vec<String> = chunk
            .iter()
            .map(|(n, a, b)| format!("({n:?}, 0x{a:X}, 0x{b:X})"))
            .collect();
        writeln!(o, "    {},", row.join(", ")).unwrap();
    }
    o.push_str("];\n");
}
